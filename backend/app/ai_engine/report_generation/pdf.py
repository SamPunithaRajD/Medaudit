"""Render a stored JSON audit report to PDF with PyMuPDF (no external services)."""
from __future__ import annotations

import fitz

PAGE_W, PAGE_H, MARGIN = 595, 842, 48


class _Writer:
    def __init__(self) -> None:
        self.doc = fitz.open()
        self.page = None
        self.y = 0.0
        self._new_page()

    def _new_page(self) -> None:
        self.page = self.doc.new_page(width=PAGE_W, height=PAGE_H)
        self.y = MARGIN

    def text(self, value: str, size: float = 9.5, bold: bool = False, gap: float = 4) -> None:
        font = "hebo" if bold else "helv"
        width = PAGE_W - 2 * MARGIN
        # Wrap by measuring words; break pages as needed.
        words = (value or "").replace("\r", "").split(" ")
        lines, cur = [], ""
        for w in words:
            for i, part in enumerate(w.split("\n")):
                if i > 0:
                    lines.append(cur)
                    cur = ""
                trial = f"{cur} {part}".strip()
                if fitz.get_text_length(trial, fontname=font, fontsize=size) > width and cur:
                    lines.append(cur)
                    cur = part
                else:
                    cur = trial
        lines.append(cur)
        for line in lines:
            if self.y + size + 2 > PAGE_H - MARGIN:
                self._new_page()
            self.page.insert_text((MARGIN, self.y + size), line, fontname=font, fontsize=size)
            self.y += size + 3
        self.y += gap

    def heading(self, value: str) -> None:
        self.text(value, size=12, bold=True, gap=2)

    def finish(self) -> bytes:
        for i, page in enumerate(self.doc, start=1):
            page.insert_text((MARGIN, PAGE_H - 20), f"MedAudit AI — confidential audit document — page {i}/{self.doc.page_count}",
                             fontsize=7)
        out = self.doc.tobytes()
        self.doc.close()
        return out


def render_pdf(report: dict) -> bytes:
    w = _Writer()
    case = report.get("case", {})
    w.text("MedAudit AI — Mortality Audit Report", size=16, bold=True)
    w.text(f"Report {report.get('report_id')} · version {report.get('report_version')} · generated {report.get('generated_at')}")
    w.text(f"Case {case.get('id')} · review status: {report.get('review_status')}")
    w.text(report.get("disclaimer", ""), size=8.5, gap=10)

    w.heading("1. Case overview")
    w.text(report.get("summary", {}).get("overview", ""))
    w.heading("2. Clinical course (provisional)")
    w.text(report.get("summary", {}).get("clinical_course", ""))

    w.heading("3. Evidence-linked findings (preliminary, require review)")
    for f in report.get("findings", []):
        pages = sorted({e.get("page_number") for e in f.get("evidence", []) if e.get("page_number")})
        w.text(f"[{f.get('severity')}] {f.get('title')} — {f.get('category')} — review: {f.get('review_status')} — "
               f"evidence: {f.get('verification_status')} (pages {', '.join(map(str, pages)) or 'n/a'})", bold=True, gap=1)
        w.text(f.get("description", ""), size=9)
    if not report.get("findings"):
        w.text("No findings were generated by the configured rules.")

    a = report.get("assessment", {})
    w.heading("4. Preliminary preventability assessment (AI-assisted, not a conclusion)")
    w.text(f"Preliminary category: {a.get('category')} · framework {a.get('framework_id')} v{a.get('framework_version')}")
    w.text(a.get("rationale", ""))
    for u in a.get("uncertainty", [])[:10]:
        w.text(f"• {u}", size=9, gap=1)

    w.heading("5. Recommendations")
    for r in report.get("recommendations", []):
        w.text(f"• [{r.get('priority')}] {r.get('description')} (status {r.get('status')}, due {r.get('due_date')})", gap=1)
    if not report.get("recommendations"):
        w.text("No recommendations recorded.")

    w.heading("6. Final committee conclusion")
    committee = report.get("sections", {}).get("16_final_committee_conclusion")
    if committee:
        w.text(f"Committee decision: {committee.get('category')} — recorded {committee.get('created_at')}")
        w.text(committee.get("rationale", ""))
    else:
        w.text("No committee decision has been recorded. Nothing in this report constitutes a committee conclusion.")

    w.heading("Source documents")
    for d in report.get("source_documents", []):
        w.text(f"{d.get('document_id')} · {d.get('page_count')} pages · SHA-256 {d.get('sha256')}", size=8)
    return w.finish()
